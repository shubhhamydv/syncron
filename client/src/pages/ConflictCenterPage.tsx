import React, { useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { api, Conflict } from '@/lib/api';
import { ConflictTable } from '@/components/conflicts/ConflictTable';
import { ConflictDrawer } from '@/components/conflicts/ConflictDrawer';
import { AlertTriangle, CheckCircle, ShieldAlert, Filter, Search, Sparkles } from 'lucide-react';

export const ConflictCenterPage: React.FC = () => {
  const [searchParams] = useSearchParams();
  const month = parseInt(searchParams.get('month') || '12', 10);
  const year = parseInt(searchParams.get('year') || '2026', 10);

  // Filter states
  const [activeTab, setActiveTab] = useState<'OPEN' | 'RESOLVED'>('OPEN');
  const [selectedSeverity, setSelectedSeverity] = useState<string>('');
  const [selectedType, setSelectedType] = useState<string>('');
  const [selectedBrandId, setSelectedBrandId] = useState<string>('');
  const [searchQuery, setSearchQuery] = useState<string>('');

  // Selected conflict for drawer
  const [selectedConflict, setSelectedConflict] = useState<Conflict | null>(null);

  // Query: Roster Metadata
  const { data: rosters, isLoading: isLoadingRoster } = useQuery({
    queryKey: ['rosters', month, year],
    queryFn: () => api.listRosters({ month, year }),
  });

  const roster = rosters?.[0] || null;

  // Query: Brands
  const { data: brands = [] } = useQuery({
    queryKey: ['brands'],
    queryFn: api.getBrands,
  });

  // Query: All Conflicts
  const {
    data: allConflicts = [],
    isLoading: isLoadingConflicts,
    refetch: refetchConflicts,
  } = useQuery({
    queryKey: ['rosterConflicts', roster?.id],
    queryFn: () => api.getConflicts(roster!.id),
    enabled: !!roster?.id,
  });

  // Count open and resolved
  const openConflicts = allConflicts.filter((c) => c.status === 'OPEN');
  const resolvedConflicts = allConflicts.filter((c) => c.status === 'RESOLVED');

  const openErrors = openConflicts.filter((c) => (c.severity || 'ERROR') === 'ERROR' && c.type !== 'PREFERENCE_VIOLATION');
  const openWarnings = openConflicts.filter((c) => c.severity === 'WARNING' || c.type === 'PREFERENCE_VIOLATION');

  const coverageGapCount = openConflicts.filter((c) => c.type === 'COVERAGE_GAP').length;
  const insufficientStaffCount = openConflicts.filter((c) => c.type === 'INSUFFICIENT_STAFF').length;
  const overlapCount = openConflicts.filter((c) => c.type === 'OVERLAP').length;

  // Filtered list based on active tab and filters
  const currentTabConflicts = activeTab === 'OPEN' ? openConflicts : resolvedConflicts;

  const filteredConflicts = currentTabConflicts.filter((c) => {
    const sev = c.severity || (c.type === 'PREFERENCE_VIOLATION' ? 'WARNING' : 'ERROR');
    if (selectedSeverity && sev !== selectedSeverity) return false;
    if (selectedType && c.type !== selectedType) return false;
    if (selectedBrandId && c.brandId !== selectedBrandId) return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      const matchBrand = c.brand?.name?.toLowerCase().includes(q) || false;
      const matchProcess = c.process?.name?.toLowerCase().includes(q) || false;
      const matchMsg = c.message.toLowerCase().includes(q);
      const matchDate = c.date.includes(q);
      if (!matchBrand && !matchProcess && !matchMsg && !matchDate) return false;
    }
    return true;
  });

  return (
    <div className="space-y-6">
      {/* Top Banner / Hero */}
      <div className="bg-white rounded-xl border border-slate-200 p-6 shadow-xs flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <ShieldAlert className="w-6 h-6 text-indigo-600" />
            <h1 className="text-xl font-bold text-slate-900">Roster Conflict Center</h1>
          </div>
          <p className="text-xs text-slate-500 mt-1 max-w-xl">
            Live diagnostic radar identifying coverage gaps, staffing shortages, and scheduling conflicts generated by pure constraint logic. Click any item to deploy AI-assisted fair replacement.
          </p>
        </div>

        {/* Tab Switcher */}
        <div className="flex items-center bg-slate-100 p-1 rounded-xl border border-slate-200 self-start md:self-auto">
          <button
            type="button"
            onClick={() => setActiveTab('OPEN')}
            className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs font-bold transition-all ${
              activeTab === 'OPEN'
                ? 'bg-white text-rose-700 shadow-xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <AlertTriangle className="w-3.5 h-3.5 text-rose-600" />
            <span>Open Issues</span>
            <span className="px-2 py-0.5 rounded-full bg-rose-100 text-rose-800 text-[10px] font-bold">
              {openConflicts.length}
            </span>
          </button>

          <button
            type="button"
            onClick={() => setActiveTab('RESOLVED')}
            className={`flex items-center gap-2 px-4 py-2 rounded-lg text-xs font-bold transition-all ${
              activeTab === 'RESOLVED'
                ? 'bg-white text-emerald-700 shadow-xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <CheckCircle className="w-3.5 h-3.5 text-emerald-600" />
            <span>Resolved History</span>
            <span className="px-2 py-0.5 rounded-full bg-emerald-100 text-emerald-800 text-[10px] font-bold">
              {resolvedConflicts.length}
            </span>
          </button>
        </div>
      </div>

      {/* KPI Severity Counters */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <div className="bg-white p-4 rounded-xl border border-rose-200 shadow-xs flex items-center justify-between">
          <div>
            <span className="text-[11px] font-semibold uppercase text-rose-600 tracking-wider">
              Critical Errors (Blocks Publish)
            </span>
            <div className="text-2xl font-bold text-rose-700 mt-1">{openErrors.length}</div>
          </div>
          <div className="w-10 h-10 rounded-xl bg-rose-50 flex items-center justify-center text-rose-600">
            <AlertTriangle className="w-5 h-5" />
          </div>
        </div>

        <div className="bg-white p-4 rounded-xl border border-amber-200 shadow-xs flex items-center justify-between">
          <div>
            <span className="text-[11px] font-semibold uppercase text-amber-600 tracking-wider">
              Soft Warnings (Non-blocking)
            </span>
            <div className="text-2xl font-bold text-amber-700 mt-1">{openWarnings.length}</div>
          </div>
          <div className="w-10 h-10 rounded-xl bg-amber-50 text-amber-600 flex items-center justify-center">
            <ShieldAlert className="w-5 h-5" />
          </div>
        </div>

        <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-xs flex items-center justify-between">
          <div>
            <span className="text-[11px] font-semibold uppercase text-slate-500 tracking-wider">
              Coverage Gaps (0 Staff)
            </span>
            <div className="text-2xl font-bold text-slate-900 mt-1">{coverageGapCount}</div>
          </div>
          <div className="w-10 h-10 rounded-xl bg-slate-100 text-slate-600 flex items-center justify-center">
            <Filter className="w-5 h-5" />
          </div>
        </div>

        <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-xs flex items-center justify-between">
          <div>
            <span className="text-[11px] font-semibold uppercase text-purple-500 tracking-wider">
              Multi-Brand Overlaps
            </span>
            <div className="text-2xl font-bold text-purple-700 mt-1">{overlapCount}</div>
          </div>
          <div className="w-10 h-10 rounded-xl bg-purple-50 text-purple-600 flex items-center justify-center">
            <Sparkles className="w-5 h-5" />
          </div>
        </div>
      </div>

      {/* Filter Toolbar */}
      <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-xs flex flex-wrap items-center justify-between gap-3">
        <div className="flex flex-wrap items-center gap-3 flex-1">
          {/* Search */}
          <div className="relative min-w-[220px]">
            <Search className="w-3.5 h-3.5 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
            <input
              type="text"
              placeholder="Search brand, process, or date..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="w-full text-xs pl-8 pr-3 py-2 rounded-lg border border-slate-200 bg-slate-50 focus:bg-white focus:outline-hidden focus:ring-1 focus:ring-indigo-500"
            />
          </div>

          {/* Severity dropdown */}
          <select
            value={selectedSeverity}
            onChange={(e) => setSelectedSeverity(e.target.value)}
            className="text-xs rounded-lg border border-slate-200 bg-slate-50 px-3 py-2 text-slate-700 focus:bg-white focus:outline-hidden focus:ring-1 focus:ring-indigo-500"
          >
            <option value="">All Severities</option>
            <option value="ERROR">Errors (Blocking)</option>
            <option value="WARNING">Warnings (Soft)</option>
          </select>

          {/* Type dropdown */}
          <select
            value={selectedType}
            onChange={(e) => setSelectedType(e.target.value)}
            className="text-xs rounded-lg border border-slate-200 bg-slate-50 px-3 py-2 text-slate-700 focus:bg-white focus:outline-hidden focus:ring-1 focus:ring-indigo-500"
          >
            <option value="">All Conflict Types</option>
            <option value="COVERAGE_GAP">Coverage Gap</option>
            <option value="INSUFFICIENT_STAFF">Insufficient Staff</option>
            <option value="OVERLAP">Multi-Brand Overlap</option>
            <option value="LEAVE_CONFLICT">Leave Conflict</option>
            <option value="PREFERENCE_VIOLATION">Preference Violation (Soft)</option>
          </select>

          {/* Brand dropdown */}
          <select
            value={selectedBrandId}
            onChange={(e) => setSelectedBrandId(e.target.value)}
            className="text-xs rounded-lg border border-slate-200 bg-slate-50 px-3 py-2 text-slate-700 focus:bg-white focus:outline-hidden focus:ring-1 focus:ring-indigo-500"
          >
            <option value="">All Brands</option>
            {brands.map((b) => (
              <option key={b.id} value={b.id}>
                {b.name}
              </option>
            ))}
          </select>

          {(selectedType || selectedBrandId || searchQuery) && (
            <button
              type="button"
              onClick={() => {
                setSelectedType('');
                setSelectedBrandId('');
                setSearchQuery('');
              }}
              className="text-xs text-indigo-600 hover:text-indigo-800 font-semibold px-2 py-1 hover:bg-indigo-50 rounded"
            >
              Reset Filters
            </button>
          )}
        </div>

        <div className="text-xs text-slate-500">
          Showing <span className="font-semibold text-slate-800">{filteredConflicts.length}</span> of {currentTabConflicts.length} {activeTab.toLowerCase()} items
        </div>
      </div>

      {/* Main Table */}
      {isLoadingRoster || isLoadingConflicts ? (
        <div className="p-12 text-center bg-white rounded-xl border border-slate-200 text-slate-500 text-sm">
          Loading conflict radar...
        </div>
      ) : (
        <ConflictTable
          conflicts={filteredConflicts}
          onSelectConflict={setSelectedConflict}
        />
      )}

      {/* Resolution Drawer */}
      <ConflictDrawer
        conflict={selectedConflict}
        onClose={() => setSelectedConflict(null)}
        onSuccess={() => {
          refetchConflicts();
        }}
      />
    </div>
  );
};
